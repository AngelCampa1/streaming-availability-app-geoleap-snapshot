    private IQueryable<SeoPage> ApplySitemapFilters(IQueryable<SeoPage> query, SitemapFilter filter)
    {
        if (filter.Status.HasValue)
            query = query.Where(p => p.Status == filter.Status.Value);

        if (filter.ModifiedAfter.HasValue)
            query = query.Where(p => p.UpdatedAt >= filter.ModifiedAfter.Value);

        if (!string.IsNullOrEmpty(filter.Category))
            query = query.Where(p => p.Category == filter.Category);

        if (filter.IndexableOnly == true)
            query = query.Where(p => p.Status == SeoPageStatus.Published);

        return query;
    }

    private string GenerateXmlSitemap(List<SeoPage> pages, SitemapGenerationRequest request)
    {
        var baseUrl = request.BaseUrl ?? "https://example.com";
        var sitemap = "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n";
        sitemap += "<urlset xmlns=\"http://www.sitemaps.org/schemas/sitemap/0.9\">\n";

        foreach (var page in pages)
        {
            sitemap += "<url>\n";
            sitemap += $"  <loc>{baseUrl}{page.Url}</loc>\n";
            sitemap += $"  <lastmod>{page.UpdatedAt:yyyy-MM-dd}</lastmod>\n";
            sitemap += $"  <priority>0.8</priority>\n";
            sitemap += "</url>\n";
        }

        sitemap += "</urlset>";
        return sitemap;
    }

