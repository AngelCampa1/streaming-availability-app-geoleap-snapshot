    public async Task<SitemapGenerationResult> GenerateSitemapAsync(SitemapGenerationRequest request, CancellationToken cancellationToken = default)
    {
        try
        {
            _logger.LogInformation("Generating sitemap with format {Format}", request.Format);

            var query = _context.Set<SeoPage>()
                .Where(p => p.Status == SeoPageStatus.Published);

            // Apply filters
            if (request.PageIds?.Any() == true)
            {
                query = query.Where(p => request.PageIds.Contains(p.Id));
            }

            if (request.Filter != null)
            {
                query = ApplySitemapFilters(query, request.Filter);
            }

            var pages = await query
                .Take(request.MaxUrls)
                .OrderByDescending(p => p.UpdatedAt)
                .ToListAsync(cancellationToken);

            string sitemapContent;
            string fileName;

            switch (request.Format)
            {
                case SitemapFormat.Xml:
                    sitemapContent = GenerateXmlSitemap(pages, request);
                    fileName = "sitemap.xml";
                    break;

                case SitemapFormat.Text:
                    sitemapContent = GenerateTextSitemap(pages, request);
                    fileName = "sitemap.txt";
                    break;

                default:
                    throw new NotSupportedException($"Sitemap format {request.Format} is not supported");
            }

            var metadata = new SitemapMetadata
            {
                GeneratedAt = DateTime.UtcNow,
                TotalUrls = pages.Count,
                ImageUrls = request.IncludeImages ? CountImageUrls(pages) : 0,
                VideoUrls = request.IncludeVideos ? CountVideoUrls(pages) : 0
            };

            return new SitemapGenerationResult
            {
                SitemapContent = sitemapContent,
                FileName = fileName,
                IncludedUrls = pages.Count,
                ExcludedUrls = Math.Max(0, await query.CountAsync(cancellationToken) - pages.Count),
                GeneratedAt = DateTime.UtcNow,
                Metadata = metadata
            };
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Error generating sitemap");
            throw new InvalidOperationException($"Sitemap generation failed: {ex.Message}", ex);
        }
    }

    public async Task<SchemaMarkupResult> GenerateSchemaMarkupAsync(SchemaGenerationRequest request, CancellationToken cancellationToken = default)
    {
        try
        {
            _logger.LogInformation("Generating schema markup for {Count} pages", request.PageIds.Count());

            var pages = await _context.Set<SeoPage>()
                .Where(p => request.PageIds.Contains(p.Id))
                .ToListAsync(cancellationToken);

            var pageSchemas = new Dictionary<string, string>();
            var validationErrors = new List<SchemaValidationError>();
            var schemaTypeCounts = new Dictionary<string, int>();

            foreach (var page in pages)
            {
                try
                {
                    var schema = await GenerateSchemaForPage(page, request.SchemaType, request.Format);
                    
                    if (request.ValidateSchema)
                    {
                        var errors = ValidateSchema(schema, page.Id.ToString());
                        validationErrors.AddRange(errors);
                    }

                    if (request.MinifyOutput)
                    {
                        schema = MinifyJsonSchema(schema);
                    }

                    pageSchemas[page.Id.ToString()] = schema;

                    // Count schema types
                    var schemaType = ExtractSchemaType(schema);
                    if (!string.IsNullOrEmpty(schemaType))
                    {
                        schemaTypeCounts[schemaType] = schemaTypeCounts.GetValueOrDefault(schemaType, 0) + 1;
                    }
                }
                catch (Exception ex)
                {
                    validationErrors.Add(new SchemaValidationError
                    {
                        PageId = page.Id.ToString(),
                        ErrorMessage = ex.Message,
                        Severity = "Error"
                    });
                }
            }

            var statistics = new SchemaStatistics
            {
                TotalSchemas = pageSchemas.Count,
                ValidSchemas = pageSchemas.Count - validationErrors.Count(e => e.Severity == "Error"),
                InvalidSchemas = validationErrors.Count(e => e.Severity == "Error"),
                SchemaTypes = schemaTypeCounts,
                TotalProperties = CalculateTotalSchemaProperties(pageSchemas.Values)
            };

            return new SchemaMarkupResult
            {
                PageSchemas = pageSchemas,
                ValidationErrors = validationErrors,
                Statistics = statistics
            };
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Error generating schema markup");
