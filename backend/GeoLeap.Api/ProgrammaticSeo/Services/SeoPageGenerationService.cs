    public async Task<SeoPage> RegeneratePageAsync(long pageId, Dictionary<string, object>? newData = null, CancellationToken cancellationToken = default)
    {
        try
        {
            _logger.LogInformation("Regenerating page with ID {PageId}", pageId);

            var existingPage = await _context.Set<SeoPage>()
                .Include(p => p.Template)
                .FirstOrDefaultAsync(p => p.Id == pageId, cancellationToken);

            if (existingPage == null)
                throw new ArgumentException($"Page with ID {pageId} not found");

            // Create new request with existing or updated data
            var request = new PageGenerationRequest
            {
                TemplateId = existingPage.TemplateId,
                Variables = newData ?? JsonSerializer.Deserialize<Dictionary<string, object>>(existingPage.VariableValues) ?? new(),
                Slug = existingPage.Slug,
                Title = existingPage.Title,
                MetaDescription = existingPage.MetaDescription,
                Status = existingPage.Status,
                OptimizeForSeo = true,
                GenerateSchemaMarkup = true,
                ValidateQuality = true
            };

            // Generate new page content
            var regeneratedPage = await GeneratePageAsync(request, cancellationToken);

            // Update existing page with new content
            existingPage.Content = regeneratedPage.Content;
            existingPage.MetaTitle = regeneratedPage.MetaTitle;
            existingPage.MetaDescription = regeneratedPage.MetaDescription;
            existingPage.H1 = regeneratedPage.H1;
            existingPage.WordCount = regeneratedPage.WordCount;
            existingPage.ReadingTimeMinutes = regeneratedPage.ReadingTimeMinutes;
            existingPage.SeoScore = regeneratedPage.SeoScore;
            existingPage.LastUpdated = DateTime.UtcNow;
            existingPage.VariableValues = regeneratedPage.VariableValues;

            await _context.SaveChangesAsync(cancellationToken);

            _logger.LogInformation("Successfully regenerated page {PageId}", pageId);
            return existingPage;
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Error regenerating page {PageId}", pageId);
            throw new InvalidOperationException($"Page regeneration failed: {ex.Message}", ex);
        }
    }

    public async Task<BulkRegenerationResult> RegeneratePagesAsync(IEnumerable<long> pageIds, RegenerationOptions? options = null, CancellationToken cancellationToken = default)
    {
        try
        {
            _logger.LogInformation("Starting bulk regeneration for {Count} pages", pageIds.Count());

            var result = new BulkRegenerationResult();
            var updatedPages = new List<SeoPage>();
            var errors = new List<RegenerationError>();

            result.TotalPages = pageIds.Count();

            foreach (var pageId in pageIds)
            {
                try
                {
                    var regeneratedPage = await RegeneratePageAsync(pageId, options?.NewData, cancellationToken);
                    updatedPages.Add(regeneratedPage);
                    result.RegeneratedPages++;
                }
                catch (ArgumentException)
                {
                    result.SkippedPages++;
                    errors.Add(new RegenerationError
                    {
                        PageId = pageId.ToString(),
                        ErrorCode = "PAGE_NOT_FOUND",
                        Message = $"Page with ID {pageId} not found"
                    });
                }
                catch (Exception ex)
                {
                    result.FailedPages++;
                    errors.Add(new RegenerationError
                    {
                        PageId = pageId.ToString(),
                        ErrorCode = "REGENERATION_FAILED",
                        Message = ex.Message
                    });
                }
            }

            result.UpdatedPages = updatedPages;
            result.Errors = errors;
            result.Duration = TimeSpan.FromSeconds(result.TotalPages * 2); // Estimated

            _logger.LogInformation("Completed bulk regeneration: {Regenerated} succeeded, {Failed} failed, {Skipped} skipped", 
                result.RegeneratedPages, result.FailedPages, result.SkippedPages);

            return result;
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Error in bulk regeneration");
            throw new InvalidOperationException($"Bulk regeneration failed: {ex.Message}", ex);
        }
    }

    public async Task<BulkOperationResult> ArchivePagesAsync(IEnumerable<long> pageIds, bool permanent = false, CancellationToken cancellationToken = default)
    {
        try
        {
            _logger.LogInformation("Archiving {Count} pages (permanent: {Permanent})", pageIds.Count(), permanent);

            var result = new BulkOperationResult();
            var affectedPages = new List<SeoPage>();
            var errors = new List<OperationError>();

            result.TotalPages = pageIds.Count();

            var pages = await _context.Set<SeoPage>()
                .Where(p => pageIds.Contains(p.Id))
                .ToListAsync(cancellationToken);

            foreach (var pageId in pageIds)
            {
                var page = pages.FirstOrDefault(p => p.Id == pageId);
                if (page == null)
                {
                    // result.SkippedItems not available in ISeoPageGenerationService BulkOperationResult
                    errors.Add(new OperationError
                    {
                        ItemId = pageId.ToString(),
                        ErrorCode = "PAGE_NOT_FOUND",
                        Message = $"Page with ID {pageId} not found"
                    });
                    continue;
                }

                try
                {
                    if (permanent)
                    {
                        _context.Set<SeoPage>().Remove(page);
                    }
                    else
                    {
                        page.Status = SeoPageStatus.Archived;
                        page.LastUpdated = DateTime.UtcNow;
                    }

                    affectedPages.Add(page);
                    result.SuccessfulOperations++;
                }
                catch (Exception ex)
                {
                    result.FailedOperations++;
                    errors.Add(new OperationError
                    {
                        ItemId = pageId.ToString(),
                        ErrorCode = "ARCHIVE_FAILED",
                        Message = ex.Message
                    });
                }
            }

            await _context.SaveChangesAsync(cancellationToken);

            // result.AffectedItems not available in ISeoPageGenerationService BulkOperationResult
            result.Errors = errors.Select(e => new BulkOperationError { PageId = e.ItemId, ErrorMessage = e.Message, Operation = "Archive" });
            result.Duration = TimeSpan.FromSeconds(result.TotalPages * 0.5); // Estimated

            _logger.LogInformation("Completed archiving: {Successful} succeeded, {Failed} failed, {Skipped} skipped", 
                result.SuccessfulOperations, result.FailedOperations, affectedPages.Count);

            return result;
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Error archiving pages");
            throw new InvalidOperationException($"Archive operation failed: {ex.Message}", ex);
        }
    }

