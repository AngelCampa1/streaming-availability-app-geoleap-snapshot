    private TimeSpan? CalculateEstimatedTimeRemaining(SeoGenerationJob job)
    {
        if (job.Status != SeoJobStatus.Running || job.ProcessedCount == 0)
            return null;

        var elapsed = DateTime.UtcNow - (job.StartedAt ?? DateTime.UtcNow);
        var avgTimePerItem = elapsed.TotalSeconds / job.ProcessedCount;
        var remainingItems = job.BatchSize - job.ProcessedCount;

        return TimeSpan.FromSeconds(avgTimePerItem * remainingItems);
    }

