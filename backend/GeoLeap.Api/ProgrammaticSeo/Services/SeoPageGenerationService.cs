    public async Task<bool> CancelGenerationAsync(string jobId, CancellationToken cancellationToken = default)
    {
        var job = await _context.Set<SeoGenerationJob>()
            .FirstOrDefaultAsync(j => j.Id == jobId, cancellationToken);

        if (job == null || job.Status == SeoJobStatus.Completed || job.Status == SeoJobStatus.Failed)
        {
            return false;
        }

        job.Status = SeoJobStatus.Cancelled;
        job.CompletedAt = DateTime.UtcNow;

        await _context.SaveChangesAsync(cancellationToken);

        _logger.LogInformation("Cancelled generation job {JobId}", jobId);
        return true;
    }

    public async Task<SeoPage> RegeneratePageAsync(string pageId, Dictionary<string, object>? newData = null, CancellationToken cancellationToken = default)
    {
        if (!long.TryParse(pageId, out var id))
        {
            throw new ArgumentException("Invalid page ID format", nameof(pageId));
        }
        
        var page = await _context.Set<SeoPage>()
            .Include(p => p.Template)
            .FirstOrDefaultAsync(p => p.Id == id, cancellationToken);

        if (page?.Template == null)
        {
            throw new InvalidOperationException($"Page or template not found: {pageId}");
        }

        // Use new data if provided, otherwise use existing data
        var variables = newData ?? page.ContentVariablesDictionary;

        // Generate new content
        var generatedContent = await _contentGenerator.GenerateContentAsync(page.Template, variables, cancellationToken);

        // Update page
        page.Content = generatedContent.Content;
        page.MetaDescription = generatedContent.MetaDescription;
        page.SchemaMarkup = generatedContent.SchemaMarkup;
        page.SeoScore = generatedContent.QualityScore.SeoOptimizationScore;
        page.ReadabilityScore = generatedContent.QualityScore.ReadabilityScore;
        page.KeywordDensityScore = generatedContent.QualityScore.KeywordDensityScore;
        page.WordCount = CountWords(generatedContent.Content);
        page.UpdatedAt = DateTime.UtcNow;

        if (newData != null)
        {
            page.ContentVariablesDictionary = newData;
        }

        await _context.SaveChangesAsync(cancellationToken);

        _logger.LogInformation("Regenerated page {PageId}", pageId);
        return page;
    }

    public async Task<BulkRegenerationResult> RegeneratePagesAsync(IEnumerable<string> pageIds, RegenerationOptions? options = null, CancellationToken cancellationToken = default)
    {
        var startTime = DateTime.UtcNow;
        var updatedPages = new List<SeoPage>();
        var errors = new List<RegenerationError>();
        var skipped = 0;

        options ??= new RegenerationOptions();

        foreach (var pageId in pageIds)
        {
            try
            {
                var page = await RegeneratePageAsync(pageId, cancellationToken: cancellationToken);
                updatedPages.Add(page);
            }
            catch (InvalidOperationException)
            {
                skipped++;
            }
            catch (Exception ex)
            {
                errors.Add(new RegenerationError
                {
                    PageId = pageId,
                    Message = ex.Message,
                    Reason = "Regeneration failed",
                    IsRecoverable = true
                });
            }
        }

        return new BulkRegenerationResult
        {
            TotalPages = pageIds.Count(),
            RegeneratedPages = updatedPages.Count,
            SkippedPages = skipped,
            FailedPages = errors.Count,
            UpdatedPages = updatedPages,
            Errors = errors,
            Duration = DateTime.UtcNow - startTime
        };
    }

    public async Task<DataSourceGenerationResult> GenerateFromDataSourceAsync(DataSourceGenerationRequest request, CancellationToken cancellationToken = default)
    {
        var jobId = Guid.NewGuid().ToString();
        var startTime = DateTime.UtcNow;

        try
        {
            _logger.LogInformation("Starting data source generation with template {TemplateId} and source type {SourceType}", 
                request.TemplateId, request.DataSource.Type);

            // Retrieve data from source
            var data = await RetrieveDataFromSource(request.DataSource, request.Filters, cancellationToken);
            
            // Map data according to configuration
            var mappedData = await MapData(data, request.DataMapping, cancellationToken);

            // Filter data if needed
            if (request.Filters != null)
            {
                mappedData = ApplyDataFilters(mappedData, request.Filters);
            }

            // Convert to batch generation request
            var batchRequest = new BatchGenerationRequest
            {
                TemplateId = request.TemplateId,
                DataSets = mappedData,
                Options = request.Options,
                NotificationEmail = request.NotificationEmail
            };

            // Process generation
            var batchResult = await GeneratePagesAsync(batchRequest, cancellationToken);

            var metrics = new DataSourceMetrics
            {
                TotalRecordsRead = data.Count(),
                DataRetrievalTime = (DateTime.UtcNow - startTime).TotalSeconds,
                DataProcessingTime = batchResult.Duration.TotalSeconds,
                DuplicateRecords = CountDuplicates(data),
                InvalidRecords = data.Count() - mappedData.Count()
            };

            return new DataSourceGenerationResult
            {
                JobId = jobId,
                TotalRecords = data.Count(),
                ProcessedRecords = mappedData.Count(),
                GeneratedPages = batchResult.SuccessfulPages,
                SkippedRecords = data.Count() - mappedData.Count(),
                Errors = ConvertToDataProcessingErrors(batchResult.Errors),
                Metrics = metrics
            };
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Error in data source generation");
            throw new InvalidOperationException($"Data source generation failed: {ex.Message}", ex);
        }
    }

    public async Task<GenerationValidationResult> ValidateGenerationRequestAsync(PageGenerationRequest request, CancellationToken cancellationToken = default)
    {
        var errors = new List<ValidationError>();
        var warnings = new List<ValidationWarning>();

        // Validate template exists
        var templateExists = await _context.Set<SeoTemplate>()
            .AnyAsync(t => t.Id == request.TemplateId && t.IsActive, cancellationToken);

        if (!templateExists)
        {
            errors.Add(new ValidationError
            {
                Code = "TEMPLATE_NOT_FOUND",
                Message = $"Template {request.TemplateId} not found or inactive"
            });
        }

        // Validate variables
        if (templateExists)
        {
            var template = await _context.Set<SeoTemplate>()
                .FirstAsync(t => t.Id == request.TemplateId, cancellationToken);

            var requiredVariables = template.VariablesList.Where(v => v.Required).Select(v => v.Name);
            foreach (var requiredVar in requiredVariables)
            {
                if (!request.Variables.ContainsKey(requiredVar))
                {
                    errors.Add(new ValidationError
                    {
                        Code = "MISSING_REQUIRED_VARIABLE",
                        Message = $"Required variable '{requiredVar}' is missing"
                    });
                }
            }
        }

        // Validate slug uniqueness if provided
        if (!string.IsNullOrEmpty(request.Slug))
        {
            var slugExists = await _context.Set<SeoPage>()
                .AnyAsync(p => p.Slug == request.Slug, cancellationToken);

            if (slugExists)
            {
                errors.Add(new ValidationError
                {
                    Code = "DUPLICATE_SLUG",
                    Message = $"Slug '{request.Slug}' already exists"
                });
            }
        }

        // Calculate complexity
        var complexity = CalculateGenerationComplexity(request);

        // Estimate resources
        var resourceEstimate = EstimateResources(request);

        return new GenerationValidationResult
        {
            IsValid = !errors.Any(),
            Errors = errors,
            Warnings = warnings,
            Complexity = complexity,
            ResourceEstimate = resourceEstimate
        };
    }

