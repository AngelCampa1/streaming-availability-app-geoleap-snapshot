    public async Task<SeoPage> GeneratePageAsync(PageGenerationRequest request, CancellationToken cancellationToken = default)
    {
        try
        {
            _logger.LogInformation("Generating SEO page with template {TemplateId}", request.TemplateId);

            // Validate request
            var validationResult = await ValidateGenerationRequestAsync(request, cancellationToken);
            if (!validationResult.IsValid)
            {
                throw new InvalidOperationException($"Invalid generation request: {string.Join(", ", validationResult.Errors.Select(e => e.Message ?? "Unknown error"))}");
            }

            // Get template
            var template = await _context.Set<SeoTemplate>()
                .FirstOrDefaultAsync(t => t.Id == request.TemplateId, cancellationToken);

            if (template == null)
            {
                throw new InvalidOperationException($"Template not found: {request.TemplateId}");
            }

            // Generate content using content generation engine
            var generatedContent = await _contentGenerator.GenerateContentAsync(template, request.Variables, cancellationToken);

            // Create SEO page
            var page = new SeoPage
            {
                // Id will be auto-generated by database
                Title = request.Title ?? generatedContent.Title,
                Slug = request.Slug ?? GenerateSlug(request.Title ?? generatedContent.Title),
                Url = GenerateUrl(request.Slug ?? GenerateSlug(request.Title ?? generatedContent.Title)),
                MetaDescription = request.MetaDescription ?? generatedContent.MetaDescription,
                MetaKeywords = string.Join(", ", request.Keywords ?? new List<string>()),
                TemplateId = request.TemplateId,
                Status = request.Status,
                Content = generatedContent.Content,
                SchemaMarkup = generatedContent.SchemaMarkup,
                ContentVariablesDictionary = request.Variables,
                KeywordsList = (request.Keywords ?? new List<string>()).ToList(),
                CreatedAt = DateTime.UtcNow,
                UpdatedAt = DateTime.UtcNow,
                PublishedAt = request.Status == SeoPageStatus.Published ? DateTime.UtcNow : null,
                SeoScore = generatedContent.QualityScore.SeoOptimizationScore,
                ReadabilityScore = generatedContent.QualityScore.ReadabilityScore,
                KeywordDensityScore = generatedContent.QualityScore.KeywordDensityScore,
                WordCount = CountWords(generatedContent.Content)
            };

            // Optimize for SEO if requested
            if (request.OptimizeForSeo)
            {
                page = await OptimizePageForSeo(page, request.Keywords?.ToList() ?? new List<string>());
            }

            // Add to database
            _context.Set<SeoPage>().Add(page);
            
            // Update template usage count
            template.UsageCount++;
            template.TotalPagesGenerated++;

            await _context.SaveChangesAsync(cancellationToken);

            // Publish immediately if requested
            if (request.PublishImmediately && page.Status == SeoPageStatus.Draft)
            {
                page.Status = SeoPageStatus.Published;
                page.PublishedAt = DateTime.UtcNow;
                await _context.SaveChangesAsync(cancellationToken);
            }

            _logger.LogInformation("Successfully generated SEO page {PageId} with title: {Title}", page.Id, page.Title);
            return page;
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Error generating SEO page with template {TemplateId}", request.TemplateId);
            throw new InvalidOperationException($"Page generation failed: {ex.Message}", ex);
        }
    }

    public async Task<BatchGenerationResult> GeneratePagesAsync(BatchGenerationRequest request, CancellationToken cancellationToken = default)
    {
        var startTime = DateTime.UtcNow;
        var generatedPages = new List<SeoPage>();
        var errors = new List<GenerationError>();

        try
        {
            _logger.LogInformation("Starting batch generation of {Count} pages with template {TemplateId}", 
                request.DataSets.Count(), request.TemplateId);

            var semaphore = new SemaphoreSlim(request.Options?.ConcurrencyLevel ?? Environment.ProcessorCount);
            var tasks = new List<Task>();

            foreach (var (dataSet, index) in request.DataSets.Select((ds, i) => (ds, i)))
            {
                tasks.Add(ProcessSinglePageGeneration(request, dataSet, index, generatedPages, errors, semaphore, cancellationToken));
                
                // Add delay between batches if specified
                if (request.Options?.DelayBetweenBatches > TimeSpan.Zero && index % request.BatchSize == 0 && index > 0)
                {
                    await Task.Delay(request.Options.DelayBetweenBatches, cancellationToken);
                }
            }

            await Task.WhenAll(tasks);

            var duration = DateTime.UtcNow - startTime;
            var metrics = CalculateBatchMetrics(generatedPages, duration);

            var result = new BatchGenerationResult
            {
                JobId = Guid.NewGuid().ToString(),
                TotalPages = request.DataSets.Count(),
                SuccessfulPages = generatedPages.Count,
                FailedPages = errors.Count,
                GeneratedPages = generatedPages,
                Errors = errors,
                Duration = duration,
                Metrics = metrics
            };

            _logger.LogInformation("Batch generation completed: {Successful}/{Total} pages generated in {Duration}", 
                result.SuccessfulPages, result.TotalPages, result.Duration);

            return result;
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Error in batch page generation");
            throw new InvalidOperationException($"Batch generation failed: {ex.Message}", ex);
        }
    }

    public async Task<string> ScheduleBatchGenerationAsync(BatchGenerationRequest request, CancellationToken cancellationToken = default)
    {
        var jobId = Guid.NewGuid().ToString();

        // Create generation job record
        var generationJob = new SeoGenerationJob
        {
            Id = jobId,
            TemplateId = request.TemplateId.ToString(),
            Status = SeoJobStatus.Pending,
            BatchSize = request.DataSets.Count(),
            Priority = request.Priority,
            CreatedAt = DateTime.UtcNow,
            Configuration = JsonSerializer.Serialize(request)
        };

        _context.Set<SeoGenerationJob>().Add(generationJob);
        await _context.SaveChangesAsync(cancellationToken);

        // Schedule background job - convert to compatible type
        var seoRequest = new SeoBatchGenerationRequest
        {
            TemplateId = request.TemplateId,
            JobName = $"Batch Job {jobId}",
            BatchSize = request.DataSets.Count()
        };
        var backgroundJobId = _backgroundJobs.Enqueue<ISeoBackgroundJobService>(
            service => service.ScheduleBatchGenerationAsync(seoRequest));

        _logger.LogInformation("Scheduled batch generation job {JobId} with background job {BackgroundJobId}", 
            jobId, backgroundJobId);

        return jobId;
    }

