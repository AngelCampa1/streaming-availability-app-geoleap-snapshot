    private double AnalyzeContentSeo(string content, List<string> keywords)
    {
        var score = 50.0;
        var wordCount = CountWords(content);
        if (wordCount >= 300) score += 25;
        if (keywords.Any(k => content.Contains(k, StringComparison.OrdinalIgnoreCase))) score += 25;
        return Math.Min(100, score);
    }

    private double AnalyzeKeywordUsage(string content, List<string> keywords)
    {
        if (!keywords.Any()) return 50;

        var wordCount = CountWords(content);
        var totalKeywordOccurrences = keywords.Sum(k => Regex.Matches(content, Regex.Escape(k), RegexOptions.IgnoreCase).Count);
        var density = (totalKeywordOccurrences / (double)wordCount) * 100;

        if (density >= 1 && density <= 3) return 100;
        if (density < 0.5 || density > 5) return 30;
        return 70;
    }

    private double AnalyzeContentStructure(string content)
    {
