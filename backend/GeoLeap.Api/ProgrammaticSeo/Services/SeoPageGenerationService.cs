    private async Task ProcessSinglePageGeneration(
        BatchGenerationRequest request, 
        Dictionary<string, object> dataSet, 
        int index,
        List<SeoPage> generatedPages, 
        List<GenerationError> errors, 
        SemaphoreSlim semaphore, 
        CancellationToken cancellationToken)
    {
        await semaphore.WaitAsync(cancellationToken);
        try
        {
            var pageRequest = new PageGenerationRequest
            {
                TemplateId = request.TemplateId,
                Variables = dataSet,
                Status = request.PublishImmediately ? SeoPageStatus.Published : SeoPageStatus.Draft,
                OptimizeForSeo = request.OptimizeForSeo,
                GenerateSchemaMarkup = request.GenerateSchemaMarkup,
                ValidateQuality = request.ValidateQuality,
                Category = request.Category,
                Author = request.Author,
                Options = request.Options
            };

            var page = await GeneratePageAsync(pageRequest, cancellationToken);
            lock (generatedPages)
            {
                generatedPages.Add(page);
            }
        }
        catch (Exception ex)
        {
            lock (errors)
            {
                errors.Add(new GenerationError
                {
                    PageId = $"batch-{index}",
                    ErrorCode = "GENERATION_FAILED",
                    Message = ex.Message,
                    StackTrace = ex.StackTrace,
                    Context = new Dictionary<string, object> { ["dataSet"] = dataSet, ["index"] = index }
                });
            }
        }
        finally
        {
            semaphore.Release();
        }
    }

