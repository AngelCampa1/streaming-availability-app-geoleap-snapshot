    public async Task<GenerationMetrics> GetGenerationMetricsAsync(TimeSpan? period = null, CancellationToken cancellationToken = default)
    {
        period ??= TimeSpan.FromDays(30);
        var startDate = DateTime.UtcNow.Subtract(period.Value);

        var pages = await _context.Set<SeoPage>()
            .Where(p => p.CreatedAt >= startDate)
            .Include(p => p.Template)
            .ToListAsync(cancellationToken);

        var totalPages = pages.Count;
        var todayPages = pages.Count(p => p.CreatedAt.Date == DateTime.UtcNow.Date);
        var weekPages = pages.Count(p => p.CreatedAt >= DateTime.UtcNow.AddDays(-7));
        var monthPages = pages.Count(p => p.CreatedAt >= DateTime.UtcNow.AddDays(-30));

        var trends = CalculateGenerationTrends(pages);
        var templateUsage = CalculateTemplateUsageMetrics(pages);
        var resourceUsage = await CalculateResourceUsage(period.Value);

        return new GenerationMetrics
        {
            TotalPagesGenerated = totalPages,
            PagesGeneratedToday = todayPages,
            PagesGeneratedThisWeek = weekPages,
            PagesGeneratedThisMonth = monthPages,
            AverageGenerationTime = CalculateAverageGenerationTime(pages),
            AverageQualityScore = pages.Any() ? pages.Average(p => p.SeoScore) : 0,
            SuccessRate = CalculateSuccessRate(pages),
            Trends = trends,
            TemplateUsage = templateUsage,
            ResourceUsage = resourceUsage
        };
    }

    public async Task<GenerationOptimizationResult> OptimizeGenerationSettingsAsync(string templateId, OptimizationCriteria criteria, CancellationToken cancellationToken = default)
    {
        try
        {
            _logger.LogInformation("Optimizing generation settings for template {TemplateId}", templateId);
            
            if (!int.TryParse(templateId, out var id))
            {
                throw new ArgumentException("Invalid template ID format", nameof(templateId));
            }

            var template = await _context.Set<SeoTemplate>()
                .FirstOrDefaultAsync(t => t.Id == id, cancellationToken);

            if (template == null)
            {
                throw new InvalidOperationException($"Template not found: {templateId}");
            }

            // Analyze current performance
            var recentPages = await _context.Set<SeoPage>()
                .Where(p => p.TemplateId == id && p.CreatedAt >= DateTime.UtcNow.AddDays(-30))
                .ToListAsync(cancellationToken);

            // Generate optimized settings based on criteria
            var optimizedSettings = new GenerationSettings
            {
                ConcurrencyLevel = DetermineOptimalConcurrency(criteria),
                Timeout = DetermineOptimalTimeout(criteria),
                BatchSize = DetermineOptimalBatchSize(criteria),
                OptimizeForSpeed = criteria.OptimizationFocus == "speed",
                OptimizeForQuality = criteria.OptimizationFocus == "quality",
                QualityThresholds = new QualityThresholds
                {
                    MinSeoScore = criteria.TargetQualityScore,
                    MinReadabilityScore = Math.Max(60.0, criteria.TargetQualityScore - 10),
                    MinWordCount = criteria.MinWordCount,
                    MaxWordCount = criteria.MaxWordCount
                }
            };

            // Generate recommendations
            var recommendations = GenerateOptimizationRecommendations(template, recentPages, criteria);

            // Calculate predicted improvement
            var currentAvgScore = recentPages.Any() ? recentPages.Average(p => p.SeoScore) : 50.0;
            var predictedImprovement = Math.Min(criteria.TargetQualityScore - currentAvgScore, 25.0);

            var metrics = new OptimizationMetrics
            {
                PerformanceScore = currentAvgScore,
                SeoScore = criteria.TargetQualityScore,
                ContentQualityScore = predictedImprovement,
                TechnicalScore = recentPages.Count,
                AnalyzedAt = DateTime.UtcNow,
                TargetEntity = "template",
                EntityId = templateId
            };

            return new GenerationOptimizationResult
            {
                TemplateId = id,
                OptimizedSettings = optimizedSettings,
                Recommendations = recommendations,
                PredictedImprovement = predictedImprovement,
                Metrics = metrics
            };
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Error optimizing generation settings for template {TemplateId}", templateId);
            throw new InvalidOperationException($"Optimization failed: {ex.Message}", ex);
        }
    }

    public async Task<PageExportResult> ExportPagesAsync(PageExportRequest request, CancellationToken cancellationToken = default)
    {
        try
        {
            _logger.LogInformation("Exporting pages with format {Format}", request.Format);

            var query = _context.Set<SeoPage>().AsQueryable();

            // Apply filters
            if (request.PageIds?.Any() == true)
            {
                query = query.Where(p => request.PageIds.Contains(p.Id));
            }

            if (request.Filter != null)
            {
                query = ApplyExportFilters(query, request.Filter);
            }

            var pages = await query.ToListAsync(cancellationToken);

            // Prepare export data
            var exportData = pages.Select(p => new
            {
                Id = p.Id,
                Title = p.Title,
                Slug = p.Slug,
                Url = p.Url,
                Content = request.IncludeContent ? p.Content : null,
                MetaDescription = p.MetaDescription,
                MetaKeywords = p.MetaKeywords,
                Status = p.Status.ToString(),
                CreatedAt = p.CreatedAt,
                UpdatedAt = p.UpdatedAt,
                PublishedAt = p.PublishedAt,
                SeoScore = p.SeoScore,
                WordCount = p.WordCount,
                Metadata = request.IncludeMetadata ? new
                {
                    TemplateId = p.TemplateId,
                    Category = p.Category,
                    Author = p.Author,
                    Variables = p.ContentVariablesDictionary,
                    Keywords = p.KeywordsList
                } : null,
                PerformanceData = request.IncludePerformanceData ? new
                {
                    SeoScore = p.SeoScore,
                    ReadabilityScore = p.ReadabilityScore,
                    KeywordDensityScore = p.KeywordDensityScore
                } : null
            });

            // Generate export content based on format
            byte[] data;
            string contentType;
            string fileName = request.FileName ?? $"pages-export-{DateTime.UtcNow:yyyyMMdd-HHmmss}";

            switch (request.Format)
            {
                case Models.ExportFormat.Json:
                    var json = JsonSerializer.Serialize(exportData, new JsonSerializerOptions { WriteIndented = true });
                    data = System.Text.Encoding.UTF8.GetBytes(json);
                    contentType = "application/json";
                    fileName += ".json";
                    break;

                case Models.ExportFormat.Csv:
                    var csv = ConvertToCsv(exportData);
                    data = System.Text.Encoding.UTF8.GetBytes(csv);
                    contentType = "text/csv";
                    fileName += ".csv";
                    break;

                case Models.ExportFormat.Xml:
                    var xml = ConvertToXml(exportData);
                    data = System.Text.Encoding.UTF8.GetBytes(xml);
                    contentType = "application/xml";
                    fileName += ".xml";
                    break;

                default:
                    throw new NotSupportedException($"Export format {request.Format} is not supported");
            }

            // Apply compression if requested
            if (request.Compression != CompressionFormat.None)
            {
                data = ApplyCompression(data, request.Compression);
                fileName += GetCompressionExtension(request.Compression);
            }

            var metadata = new ExportMetadata
            {
                ExportedAt = DateTime.UtcNow,
                ExportedBy = "system",
                Version = "1.0",
                FileSize = data.Length
            };

            return new PageExportResult
            {
                FileName = fileName,
                ContentType = contentType,
                Data = data,
                ExportedPagesCount = pages.Count,
                Metadata = metadata
            };
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Error exporting pages");
            throw new InvalidOperationException($"Export failed: {ex.Message}", ex);
        }
    }

    public async Task<PageImportResult> ImportPagesAsync(PageImportRequest request, CancellationToken cancellationToken = default)
    {
        try
        {
            _logger.LogInformation("Importing pages from {FileName} with format {Format}", request.FileName, request.Format);

            var importedPages = new List<SeoPage>();
            var errors = new List<ImportError>();
            var skipped = 0;

            // Parse import data based on format
            var importData = ParseImportData(request.Data, request.Format);

            foreach (var (item, index) in importData.Select((item, i) => (item, i)))
            {
                try
                {
                    if (request.ValidateBeforeImport)
                    {
                        var validationErrors = ValidateImportItem(item);
                        if (validationErrors.Any())
                        {
                            errors.AddRange(validationErrors.Select(e => new ImportError
                            {
                                LineNumber = index + 1,
                                ErrorType = "Validation",
                                Message = e
                            }));
                            continue;
                        }
                    }

                    // Check for existing page
                    var existingPage = await _context.Set<SeoPage>()
                        .FirstOrDefaultAsync(p => p.Slug == item.Slug || p.Id.ToString() == item.Id, cancellationToken);

                    if (existingPage != null && !request.OverwriteExisting)
                    {
                        skipped++;
                        continue;
                    }

                    // Create or update page
                    var page = existingPage ?? new SeoPage { Id = !string.IsNullOrEmpty(item.Id) && long.TryParse(item.Id, out var parsedId) ? parsedId : 0 };

                    page.Title = item.Title;
                    page.Slug = item.Slug;
                    page.Url = item.Url ?? GenerateUrl(item.Slug);
                    page.Content = item.Content;
                    page.MetaDescription = item.MetaDescription;
                    page.MetaKeywords = item.MetaKeywords;
                    page.TemplateId = !string.IsNullOrEmpty(item.TemplateId) && int.TryParse(item.TemplateId, out var templateId) ? templateId : (!string.IsNullOrEmpty(request.DefaultTemplate) && int.TryParse(request.DefaultTemplate, out var defaultTemplateId) ? defaultTemplateId : 0);
                    page.Status = Enum.TryParse<SeoPageStatus>(item.Status, out var status) ? status : SeoPageStatus.Draft;
                    page.UpdatedAt = DateTime.UtcNow;

                    if (existingPage == null)
                    {
                        page.CreatedAt = item.CreatedAt ?? DateTime.UtcNow;
                        _context.Set<SeoPage>().Add(page);
                    }

                    importedPages.Add(page);
                }
                catch (Exception ex)
                {
                    errors.Add(new ImportError
                    {
                        LineNumber = index + 1,
                        ErrorType = "Processing",
                        Message = ex.Message
                    });
                }
            }

            await _context.SaveChangesAsync(cancellationToken);

            var metadata = new ImportMetadata
            {
                ImportedAt = DateTime.UtcNow,
                SourceFileName = request.FileName,
                OriginalFileSize = request.Data.Length,
                ProcessingTime = TimeSpan.FromSeconds(1) // Simplified
            };

            return new PageImportResult
            {
                TotalPages = importData.Count(),
                ImportedPages = importedPages.Count,
                SkippedPages = skipped,
                FailedPages = errors.Count,
                ImportedPagesList = importedPages,
                Errors = errors,
                Metadata = metadata
            };
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Error importing pages");
            throw new InvalidOperationException($"Import failed: {ex.Message}", ex);
        }
    }

    public async Task<BulkOperationResult> ArchivePagesAsync(IEnumerable<string> pageIds, bool permanent = false, CancellationToken cancellationToken = default)
    {
        var startTime = DateTime.UtcNow;
        var errors = new List<BulkOperationError>();
        var successCount = 0;

        try
        {
            _logger.LogInformation("Archiving {Count} pages (permanent: {Permanent})", pageIds.Count(), permanent);

            foreach (var pageId in pageIds)
            {
                try
                {
                    var page = await _context.Set<SeoPage>()
                        .FirstOrDefaultAsync(p => p.Id.ToString() == pageId, cancellationToken);

                    if (page == null)
                    {
                        errors.Add(new BulkOperationError
                        {
                            PageId = pageId,
                            Operation = "Archive",
                            ErrorMessage = "Page not found",
                            IsRetryable = false
                        });
                        continue;
                    }

                    if (permanent)
                    {
                        _context.Set<SeoPage>().Remove(page);
                    }
                    else
                    {
                        page.Status = SeoPageStatus.Archived;
                        page.UpdatedAt = DateTime.UtcNow;
                    }

                    successCount++;
                }
                catch (Exception ex)
                {
                    errors.Add(new BulkOperationError
                    {
                        PageId = pageId,
                        Operation = "Archive",
                        ErrorMessage = ex.Message,
                        IsRetryable = true
                    });
                }
            }

            await _context.SaveChangesAsync(cancellationToken);

            return new BulkOperationResult
            {
                TotalPages = pageIds.Count(),
                SuccessfulOperations = successCount,
                FailedOperations = errors.Count,
                Errors = errors,
                Duration = DateTime.UtcNow - startTime
            };
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Error in bulk archive operation");
            throw new InvalidOperationException($"Bulk archive failed: {ex.Message}", ex);
        }
