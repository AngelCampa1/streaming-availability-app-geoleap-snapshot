    private string ExtractSchemaType(string schema)
    {
        try
        {
            using var doc = JsonDocument.Parse(schema);
            if (doc.RootElement.TryGetProperty("@type", out var typeElement) ||
                doc.RootElement.TryGetProperty("type", out typeElement))
            {
                return typeElement.GetString() ?? "Unknown";
            }
        }
        catch
        {
            // Ignore parsing errors
        }
        return "Unknown";
    }

    private int CalculateTotalSchemaProperties(IEnumerable<string> schemas)
    {
        return schemas.Sum(schema =>
        {
            try
            {
                using var doc = JsonDocument.Parse(schema);
                return CountJsonProperties(doc.RootElement);
            }
            catch
            {
                return 0;
            }
        });
    }

    private int CountJsonProperties(JsonElement element)
    {
        return element.ValueKind switch
        {
            JsonValueKind.Object => element.EnumerateObject().Sum(prop => 1 + CountJsonProperties(prop.Value)),
            JsonValueKind.Array => element.EnumerateArray().Sum(CountJsonProperties),
            _ => 0
        };
    }

    private double CalculateThroughput(List<SeoPage> pages)
    {
        if (!pages.Any()) return 0;
        var timeSpan = pages.Max(p => p.CreatedAt) - pages.Min(p => p.CreatedAt);
        return timeSpan.TotalHours > 0 ? pages.Count / timeSpan.TotalHours : 0;
    }

